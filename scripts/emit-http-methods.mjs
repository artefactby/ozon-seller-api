/**
 * Emits src/generated/http-methods.ts from the OpenAPI spec.
 *
 * The typed core knows a path's HTTP method from the type system, but the
 * runtime needs it too. The spec uses exactly one method per path, and all but
 * a handful are POST, so we emit the small set of GET paths and treat POST as
 * the default. If a spec update ever introduces another method, this script
 * fails instead of silently sending the wrong request.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { HTTP_METHODS as OUT, SPEC } from './lib/paths.mjs';

const SUPPORTED = new Set(['get', 'post']);

const spec = JSON.parse(readFileSync(SPEC, 'utf8'));
const getPaths = [];
const templatedPaths = [];

for (const [path, item] of Object.entries(spec.paths ?? {})) {
  if (path.includes('{')) templatedPaths.push(path);
  const methods = Object.keys(item).filter((key) => key !== 'parameters' && key !== 'servers');

  const unsupported = methods.filter((method) => !SUPPORTED.has(method));
  if (unsupported.length > 0) {
    throw new Error(
      `${path} uses unsupported method(s): ${unsupported.join(', ')}. ` +
        'Teach the client about them before regenerating.',
    );
  }
  if (methods.length !== 1) {
    throw new Error(
      `${path} declares ${methods.length} methods (${methods.join(', ')}); ` +
        'the client assumes exactly one method per path.',
    );
  }
  if (methods[0] === 'get') getPaths.push(path);
}

getPaths.sort();

const contents = `/**
 * This file was auto-generated by scripts/emit-http-methods.mjs.
 * Do not make direct changes to the file.
 */

/**
 * Paths served over GET. Every other path in the spec is POST, which is what
 * the client falls back to.
 */
export const GET_PATHS: ReadonlySet<string> = new Set([
${getPaths.map((path) => `  '${path}',`).join('\n')}
]);
`;

writeFileSync(OUT, contents);
console.log(`${SPEC} → ${OUT} [${getPaths.length} GET paths, POST default]`);

// A templated path cannot be called through the typed request(): the URL with
// the parameter substituted no longer matches the spec literal, so the method
// lookup misses too. Consumers go through requestRaw with an explicit method.
// Keep the README's escape-hatch section in sync with this list.
if (templatedPaths.length > 0) {
  console.warn(
    `warning: ${templatedPaths.length} templated path(s) need requestRaw with an explicit method:\n` +
      templatedPaths.map((path) => `  ${path}`).join('\n'),
  );
}
